import { Container, PlannedContainer, Vehicle } from '../types';

/**
 * Formats a container plan into a WhatsApp-friendly message.
 * Optimized for readability on mobile screens with vehicle specs and totals.
 */
export function formatContainerForWhatsApp(container: Container | PlannedContainer): string {
  const cNo = container.containerNo || 'TBA';
  const seal = container.sealOrBlNo || 'N/A';
  const extra = container.extraValue || 'N/A';
  const vehicles = container.vehicles || [];

  const lines: string[] = [];
  lines.push(`🚢 *CONTAINER LOADING PLAN*`);
  lines.push(`━━━━━━━━━━━━━━━━━━━━━`);
  lines.push(`📦 *Container No:* \`${cNo}\``);
  lines.push(`🔒 *Seal / B/L No:* \`${seal}\``);
  lines.push(`⚖️ *Tare / Extra:* \`${extra} kg\``);
  lines.push(`🚗 *Total Vehicles:* ${vehicles.length}`);
  lines.push(``);
  lines.push(`📋 *VEHICLE MANIFEST:*`);

  vehicles.forEach((v: Vehicle, i: number) => {
    const sNo = v.serialNo || i + 1;
    const fuelLabel = v.fuel === 'D' ? 'Diesel' : v.fuel === 'G' ? 'Petrol' : v.fuel;
    lines.push(`*#${sNo} ${v.make} ${v.model}* (${v.year || ''})`);
    lines.push(`   • Chassis: \`${v.chassisNo || 'N/A'}\``);
    lines.push(`   • Prefix: \`${v.chassisPrefix || 'N/A'}\` | CC: ${v.engineCC || '-'} | ${fuelLabel}`);
    lines.push(`   • Dims: ${v.length}×${v.width}×${v.height} cm`);
    lines.push(`   • CBM: ${v.cbm?.toFixed(3)} m³ | Wt: ${v.weight} kg`);
    if (v.price) {
      lines.push(`   • Price: ¥${v.price.toLocaleString()}`);
    }
    lines.push(``);
  });

  lines.push(`━━━━━━━━━━━━━━━━━━━━━`);
  lines.push(`📊 *CONTAINER TOTALS:*`);
  lines.push(`   • Total CBM: *${container.totalCbm?.toFixed(3)} m³*`);
  lines.push(`   • Total Weight: *${container.totalWeight?.toLocaleString()} kg*`);
  if (container.totalPrice) {
    lines.push(`   • Total Value: *¥${container.totalPrice.toLocaleString()}*`);
  }
  lines.push(`━━━━━━━━━━━━━━━━━━━━━`);
  lines.push(`Generated by *Container Plan Manager* (Japan Export)`);

  return lines.join('\n');
}

/**
 * Copies text to clipboard and returns true if succeeded.
 */
export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    } else {
      const textarea = document.createElement('textarea');
      textarea.value = text;
      textarea.style.position = 'fixed';
      textarea.style.left = '-9999px';
      document.body.appendChild(textarea);
      textarea.focus();
      textarea.select();
      const successful = document.execCommand('copy');
      document.body.removeChild(textarea);
      return successful;
    }
  } catch (err) {
    console.error('Failed to copy to clipboard', err);
    return false;
  }
}
